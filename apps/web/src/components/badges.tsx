const CLAIM_LABELS: Record<string, { label: string; tone: string; title: string }> = {
  source_fact: {
    label: 'Source fact',
    tone: 'fact',
    title: 'Stated by the cited source.',
  },
  provider_fact: {
    label: 'Provider fact',
    tone: 'fact',
    title: 'Asserted by a data provider; see the cited evidence.',
  },
  model_inference: {
    label: 'Model inference',
    tone: 'inference',
    title: 'Generated by a model. Not a sourced fact; verify before relying on it.',
  },
  user_assertion: {
    label: 'User assertion',
    tone: 'neutral',
    title: 'Entered by a user in this workspace.',
  },
};

export function ClaimTypeBadge({ type }: { type: string }) {
  const meta = CLAIM_LABELS[type] ?? { label: type, tone: 'neutral', title: type };
  return (
    <span className={`badge badge-${meta.tone}`} title={meta.title}>
      {meta.label}
    </span>
  );
}

export function ConfidenceBadge({
  confidence,
}: {
  confidence: { value: number; band: string; explanation: string };
}) {
  return (
    <span className={`badge badge-conf-${confidence.band}`} title={confidence.explanation}>
      {confidence.band.replace('_', ' ')} · {Math.round(confidence.value * 100)}%
    </span>
  );
}

export function StatusBadge({ status }: { status: string }) {
  return <span className={`badge badge-status-${status}`}>{status.replace(/_/g, ' ')}</span>;
}

export function MockBadge() {
  return (
    <span className="badge badge-mock" title="Synthetic data from a deterministic mock provider.">
      Mock data
    </span>
  );
}
